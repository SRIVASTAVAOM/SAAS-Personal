import 'package:flutter/material.dart';
import 'package:flutter_bloc/flutter_bloc.dart';
import '../bloc/exams_bloc.dart';
import '../models/exam_model.dart';

class ClassReportCardsView extends StatefulWidget {
  final String examId;
  final String examName;
  final String classId;
  final String sectionId;
  final bool isCoordinator;

  const ClassReportCardsView({
    super.key,
    required this.examId,
    required this.examName,
    required this.classId,
    required this.sectionId,
    this.isCoordinator = false,
  });

  @override
  State<ClassReportCardsView> createState() => _ClassReportCardsViewState();
}

class _ClassReportCardsViewState extends State<ClassReportCardsView> {
  @override
  void initState() {
    super.initState();
    context.read<ExamsBloc>().add(
          LoadClassReportCardsEvent(widget.examId, widget.classId, widget.sectionId),
        );
  }

  void _generateCards() {
    context.read<ExamsBloc>().add(
          GenerateReportCardsEvent(
            widget.examId,
            widget.classId,
            widget.sectionId,
            remarks: 'Generated by Class Teacher',
          ),
        );
  }

  void _approveCards() {
    context.read<ExamsBloc>().add(
          ApproveReportCardsEvent(widget.examId, widget.classId, widget.sectionId),
        );
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(
        title: Text('${widget.examName} - Report Cards'),
        elevation: 0,
        backgroundColor: Colors.white,
        foregroundColor: Colors.black87,
        actions: [
          IconButton(
            icon: const Icon(Icons.refresh),
            onPressed: () {
              context.read<ExamsBloc>().add(
                    LoadClassReportCardsEvent(widget.examId, widget.classId, widget.sectionId),
                  );
            },
          ),
        ],
        bottom: PreferredSize(
          preferredSize: const Size.fromHeight(1.0),
          child: Container(color: Colors.grey.shade200, height: 1.0),
        ),
      ),
      backgroundColor: const Color(0xFFF9FAFB),
      body: BlocConsumer<ExamsBloc, ExamsState>(
        listener: (context, state) {
          if (state is ExamOperationSuccess) {
            ScaffoldMessenger.of(context).showSnackBar(
              SnackBar(content: Text(state.message), backgroundColor: Colors.black87),
            );
          } else if (state is ExamsError) {
            ScaffoldMessenger.of(context).showSnackBar(
              SnackBar(content: Text(state.message), backgroundColor: Colors.red.shade700),
            );
          }
        },
        builder: (context, state) {
          if (state is ExamsLoading) {
            return const Center(child: CircularProgressIndicator(strokeWidth: 2));
          }

          if (state is ClassReportCardsLoaded) {
            final cards = state.reportCards;

            return Column(
              children: [
                _buildActionBanner(cards),
                Expanded(
                  child: cards.isEmpty
                      ? Center(
                          child: Column(
                            mainAxisAlignment: MainAxisAlignment.center,
                            children: [
                              Icon(Icons.assignment_outlined, size: 48, color: Colors.grey.shade400),
                              const SizedBox(height: 12),
                              Text(
                                'No report cards generated yet.',
                                style: TextStyle(color: Colors.grey.shade600, fontSize: 14),
                              ),
                              const SizedBox(height: 16),
                              ElevatedButton(
                                onPressed: _generateCards,
                                style: ElevatedButton.styleFrom(
                                  backgroundColor: Colors.black87,
                                  foregroundColor: Colors.white,
                                  elevation: 0,
                                ),
                                child: const Text('Generate Class Report Cards'),
                              ),
                            ],
                          ),
                        )
                      : ListView.separated(
                          padding: const EdgeInsets.all(16),
                          itemCount: cards.length,
                          separatorBuilder: (_, _) => const SizedBox(height: 10),
                          itemBuilder: (context, index) {
                            final card = cards[index];
                            return _buildReportCardTile(card);
                          },
                        ),
                ),
              ],
            );
          }

          return const SizedBox.shrink();
        },
      ),
    );
  }

  Widget _buildActionBanner(List<ReportCardModel> cards) {
    if (cards.isEmpty) return const SizedBox.shrink();

    final allApproved = cards.every((c) => c.status == 'APPROVED');

    return Container(
      padding: const EdgeInsets.all(16),
      color: Colors.white,
      child: Row(
        children: [
          Expanded(
            child: OutlinedButton.icon(
              onPressed: _generateCards,
              icon: const Icon(Icons.refresh, size: 16, color: Colors.black87),
              label: const Text('Re-calculate', style: TextStyle(color: Colors.black87)),
              style: OutlinedButton.styleFrom(
                side: const BorderSide(color: Colors.black87),
                shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(6)),
              ),
            ),
          ),
          if (widget.isCoordinator && !allApproved) ...[
            const SizedBox(width: 12),
            Expanded(
              child: ElevatedButton.icon(
                onPressed: _approveCards,
                icon: const Icon(Icons.check_circle_outline, size: 16),
                label: const Text('Approve All'),
                style: ElevatedButton.styleFrom(
                  backgroundColor: Colors.black87,
                  foregroundColor: Colors.white,
                  elevation: 0,
                  shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(6)),
                ),
              ),
            ),
          ],
        ],
      ),
    );
  }

  Widget _buildReportCardTile(ReportCardModel card) {
    final isApproved = card.status == 'APPROVED';

    return Container(
      padding: const EdgeInsets.all(14),
      decoration: BoxDecoration(
        color: Colors.white,
        borderRadius: BorderRadius.circular(8),
        border: Border.all(color: Colors.grey.shade200),
      ),
      child: Row(
        children: [
          CircleAvatar(
            radius: 18,
            backgroundColor: Colors.grey.shade100,
            child: Text(
              card.rollNumber ?? '-',
              style: const TextStyle(fontWeight: FontWeight.bold, fontSize: 13, color: Colors.black87),
            ),
          ),
          const SizedBox(width: 12),
          Expanded(
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Text(
                  card.studentName ?? 'Student',
                  style: const TextStyle(fontWeight: FontWeight.w600, fontSize: 15),
                ),
                const SizedBox(height: 2),
                Text(
                  '${card.totalMarksObtained.toStringAsFixed(1)} / ${card.totalMaxMarks.toStringAsFixed(1)} marks',
                  style: TextStyle(fontSize: 13, color: Colors.grey.shade600),
                ),
              ],
            ),
          ),
          Column(
            crossAxisAlignment: CrossAxisAlignment.end,
            children: [
              Text(
                '${card.percentage.toStringAsFixed(1)}%',
                style: const TextStyle(fontWeight: FontWeight.bold, fontSize: 16),
              ),
              const SizedBox(height: 4),
              Container(
                padding: const EdgeInsets.symmetric(horizontal: 6, vertical: 2),
                decoration: BoxDecoration(
                  color: isApproved ? Colors.green.shade50 : Colors.blue.shade50,
                  borderRadius: BorderRadius.circular(4),
                  border: Border.all(color: isApproved ? Colors.green.shade200 : Colors.blue.shade200),
                ),
                child: Text(
                  card.status,
                  style: TextStyle(
                    fontSize: 10,
                    fontWeight: FontWeight.w600,
                    color: isApproved ? Colors.green.shade800 : Colors.blue.shade800,
                  ),
                ),
              ),
            ],
          ),
        ],
      ),
    );
  }
}
